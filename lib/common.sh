#!/usr/bin/env bash
# ============================================================================
#  공통 설정 · 공통 함수
# ----------------------------------------------------------------------------
#  이 파일은 직접 실행하지 않습니다.
#  new-site.sh / publish.sh / protect.sh / remove-site.sh 가 맨 위에서
#  source 로 불러다 씁니다. ("source" 는 다른 파일의 내용을 그대로
#  가져와서 실행하는 명령입니다.)
#
#  여기서 하는 일은 크게 세 가지입니다.
#    1) gh(깃허브 명령도구) 와 vercel(버셀 명령도구) 의 위치를 찾는다
#    2) 내 계정 정보(깃허브 아이디, 버셀 팀 이름)를 알아낸다
#    3) 여러 스크립트가 함께 쓰는 작은 도우미 함수들을 정의한다
# ============================================================================

# ----------------------------------------------------------------------------
# set -euo pipefail : 스크립트를 "엄격 모드"로 돌린다는 뜻입니다.
#   -e          명령이 하나라도 실패하면 즉시 중단 (오류를 못 보고 지나치는 것 방지)
#   -u          정의하지 않은 변수를 쓰면 오류 (오타로 인한 사고 방지)
#   -o pipefail 파이프(|)로 이어진 명령 중 하나라도 실패하면 실패로 처리
# 초보자에게 특히 유용합니다. 잘못된 상태로 계속 진행하지 않게 막아줍니다.
# ----------------------------------------------------------------------------
set -euo pipefail

# ----------------------------------------------------------------------------
# MSYS_NO_PATHCONV
#   윈도우의 Git Bash 는 "/v9/projects" 같은 문자열을 파일 경로로 오해해서
#   "C:/Program Files/Git/v9/projects" 로 멋대로 바꿔버립니다.
#   버셀 API 주소를 넘길 때 이것 때문에 오류가 납니다. 그래서 변환을 끕니다.
#   (맥/리눅스에서는 이 변수가 아무 영향도 주지 않으니 그냥 둬도 됩니다.)
# ----------------------------------------------------------------------------
export MSYS_NO_PATHCONV=1

# 이 파일이 있는 폴더 = 도구 폴더. 어디서 실행하든 경로를 잃지 않게 계산해 둡니다.
TOOLS="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CONFIG_FILE="$TOOLS/config.sh"
export TOOLS CONFIG_FILE

# ----------------------------------------------------------------------------
# 화면 출력 도우미
#   step  : 진행 단계를 "▸ ..." 모양으로 보여줍니다
#   die   : 오류 메시지를 보여주고 스크립트를 중단합니다
#   note  : 참고 메시지 (들여쓰기해서 보여줌)
# ----------------------------------------------------------------------------
step() { printf '▸ %s\n' "$*"; }
die()  { printf '\n✖ %s\n' "$*" >&2; exit 1; }
note() { printf '  %s\n' "$*"; }
export -f step die note

# ----------------------------------------------------------------------------
# gh 실행파일 찾기
#   보통은 PATH 에 등록되어 "gh" 만 쳐도 되지만,
#   윈도우 winget 으로 설치하면 PATH 등록이 셸 재시작 후에야 반영됩니다.
#   그래서 흔한 설치 위치들을 차례로 뒤져봅니다.
# ----------------------------------------------------------------------------
find_gh() {
  # 1순위: PATH 에 있으면 그걸 씀
  if command -v gh >/dev/null 2>&1; then command -v gh; return; fi
  # 2순위: 흔한 설치 경로들
  local candidates=(
    "$HOME/AppData/Local/Microsoft/WinGet/Packages"/GitHub.cli_*/bin/gh.exe
    "/c/Program Files/GitHub CLI/gh.exe"
    "/c/Program Files (x86)/GitHub CLI/gh.exe"
    "/opt/homebrew/bin/gh"
    "/usr/local/bin/gh"
    "/usr/bin/gh"
  )
  local c
  for c in "${candidates[@]}"; do
    [ -x "$c" ] && { printf '%s' "$c"; return; }
  done
  return 1
}

# ----------------------------------------------------------------------------
# vercel 실행파일 찾기 (npm 으로 전역 설치되면 PATH 에 잡힙니다)
# ----------------------------------------------------------------------------
find_vercel() {
  if command -v vercel >/dev/null 2>&1; then command -v vercel; return; fi
  return 1
}

GH="$(find_gh || true)"
VERCEL="$(find_vercel || true)"
export GH VERCEL

# ----------------------------------------------------------------------------
# config.sh 불러오기
#   setup.sh 가 만들어 두는 파일입니다. 내 깃허브 아이디, 버셀 팀 이름,
#   새 프로젝트를 만들 기본 폴더가 적혀 있습니다.
#   없으면 setup.sh 를 먼저 돌리라고 안내합니다.
# ----------------------------------------------------------------------------
if [ -f "$CONFIG_FILE" ]; then
  # shellcheck disable=SC1090
  source "$CONFIG_FILE"
fi

# 값이 비어 있으면 그때그때 물어보지 않고 계정에서 직접 알아냅니다.
: "${GH_OWNER:=}"
: "${VERCEL_SCOPE:=}"
: "${GIT_NAME:=}"
: "${GIT_EMAIL:=}"
: "${DEFAULT_PARENT:=$HOME/sites}"
export GH_OWNER VERCEL_SCOPE GIT_NAME GIT_EMAIL DEFAULT_PARENT

# ----------------------------------------------------------------------------
# require_tools : 도구가 설치되어 있는지 확인
#   없으면 setup.sh 를 돌리라고 알려주고 멈춥니다.
# ----------------------------------------------------------------------------
require_tools() {
  [ -n "$GH" ]     || die "gh(깃허브 명령도구)를 찾을 수 없습니다.  먼저 실행:  bash setup.sh"
  [ -n "$VERCEL" ] || die "vercel(버셀 명령도구)를 찾을 수 없습니다.  먼저 실행:  bash setup.sh"
}

# ----------------------------------------------------------------------------
# check_auth : 로그인이 살아있는지 확인
#   토큰이 만료되거나 로그아웃된 상태에서 작업을 시작하면
#   중간에 이상한 오류가 나므로, 시작 전에 미리 막습니다.
# ----------------------------------------------------------------------------
check_auth() {
  require_tools
  "$GH" auth status >/dev/null 2>&1 \
    || die "깃허브 로그인이 필요합니다.  실행:  bash setup.sh"
  "$VERCEL" whoami >/dev/null 2>&1 \
    || die "버셀 로그인이 필요합니다.  실행:  bash setup.sh"

  # 설정 파일에 값이 없으면 계정에서 읽어와 채웁니다.
  [ -n "$GH_OWNER" ]  || GH_OWNER="$("$GH" api /user --jq .login 2>/dev/null || true)"
  [ -n "$GIT_NAME" ]  || GIT_NAME="$GH_OWNER"
  [ -n "$GIT_EMAIL" ] || GIT_EMAIL="$("$GH" api /user --jq '.email // ""' 2>/dev/null || true)"
  [ -n "$GIT_EMAIL" ] || GIT_EMAIL="$GH_OWNER@users.noreply.github.com"
  export GH_OWNER GIT_NAME GIT_EMAIL
}

# ----------------------------------------------------------------------------
# vercel_scope_args : 버셀 명령에 붙일 --scope 옵션을 만들어 줍니다.
#   개인 계정만 쓰는 사람은 팀 이름이 없을 수 있어서, 비어 있으면 아무것도
#   붙이지 않습니다. (--scope "" 로 넘기면 오류가 납니다.)
# ----------------------------------------------------------------------------
vercel_scope_args() {
  if [ -n "$VERCEL_SCOPE" ]; then printf -- '--scope\n%s\n' "$VERCEL_SCOPE"; fi
}

# vercel 을 scope 옵션과 함께 실행하는 짧은 이름
vc() {
  local args=()
  if [ -n "$VERCEL_SCOPE" ]; then args=(--scope "$VERCEL_SCOPE"); fi
  "$VERCEL" "$@" "${args[@]}"
}

# ----------------------------------------------------------------------------
# winpath : 파일 경로를 윈도우 프로그램이 알아듣는 형태로 바꾼다
#
#   ★ 윈도우에서만 필요한 처리입니다 ★
#   Git Bash 안에서 경로는 "/c/Users/이름/..." 처럼 보이지만,
#   vercel 같은 윈도우 프로그램은 이걸 못 읽습니다. "C:/Users/이름/..." 이어야
#   합니다. cygpath 라는 변환 도구가 그 일을 해줍니다.
#   (맥·리눅스에는 cygpath 가 없고 변환도 필요 없으므로 그대로 돌려줍니다.)
# ----------------------------------------------------------------------------
winpath() {
  if command -v cygpath >/dev/null 2>&1; then
    cygpath -m "$1"          # -m : C:/Users/... 형태 (슬래시 유지)
  else
    printf '%s' "$1"
  fi
}

# ----------------------------------------------------------------------------
# to_slug : 이름을 깃허브·버셀이 받는 형태로 바꿉니다 (한글이면 로마자로)
#
#   ★ 왜 필요한가 ★
#     깃허브는 한글 저장소 이름을 전부 버리고 "-" 한 글자로 만들어 버리고,
#     버셀은 한글 폴더에서 "Detected linked project does not have id" 오류를
#     냅니다. 둘 다 실제로 겪은 문제입니다.
#
#     예전에는 한글 이름이면 그냥 막았는데, 막는 것보다 자동으로 바꿔주는
#     편이 낫습니다. 소리나는 대로 로마자로 옮깁니다.
#         포트폴리오 → poteupolrio      대전 서구 상권 → daejeon-seogu-sanggwon
#
#   변환은 lib/slug.js 가 합니다. Node.js 로 만든 이유는, 이 도구가 vercel
#   설치에 Node.js 를 요구하므로 이미 반드시 깔려 있기 때문입니다.
# ----------------------------------------------------------------------------
to_slug() {
  local n="$1"
  # 이미 올바른 형태면 그대로 씁니다 (쓸데없이 node 를 부르지 않습니다)
  if printf '%s' "$n" | grep -qE '^[a-z0-9][a-z0-9-]{0,62}$'; then
    printf '%s' "$n"; return 0
  fi
  command -v node >/dev/null 2>&1 || return 1
  # node 는 윈도우 프로그램이라 "/c/Users/..." 를 못 읽습니다. winpath 로 바꿔 넘깁니다.
  node "$(winpath "$TOOLS/lib/slug.js")" "$n" 2>/dev/null || return 1
}

# check_name : 이름을 확인하고, 필요하면 바꿔서 돌려줍니다.
#   바뀐 경우 사용자에게 무엇으로 바뀌었는지 알려 줍니다.
#   변환해도 쓸 수 없으면(빈 이름, 기호만 등) 그때만 멈춥니다.
check_name() {
  local n="$1" s
  s="$(to_slug "$n" || true)"
  if [ -z "$s" ]; then
    die "이 이름은 쓸 수 없습니다: '$n'
  저장소 이름에는 글자나 숫자가 하나는 있어야 합니다.
  예)  bash new-site.sh my-site --title \"내 사이트\""
  fi
  if [ "$s" != "$n" ]; then
    # 안내는 화면(stderr)으로 보냅니다. stdout 으로 보내면 결과값에 섞여
    # $(check_name ...) 로 받을 때 안내 문구까지 이름이 되어 버립니다.
    note "이름 '$n' 은 깃허브에서 쓸 수 없어 '$s' 로 바꿨습니다." >&2
    note "(화면에 보이는 제목은 그대로 '$n' 입니다.)" >&2
  fi
  printf '%s' "$s"
}

# ----------------------------------------------------------------------------
# site_url : 버셀 프로젝트의 대표 주소를 알아냅니다.
# ----------------------------------------------------------------------------
#   주의: 아래 함수들은 "못 찾는 것"이 정상인 경우가 있습니다.
#   (예: grep 이 제목을 못 찾음 = 배포가 없음)
#   set -e / pipefail 때문에 그때 스크립트 전체가 죽지 않도록
#   모든 파이프라인 끝에 || true 를 붙여 실패를 흡수합니다.
#   ★ 함정 ★ vercel 은 목록 표를 stdout 이 아니라 stderr 로 내보냅니다.
#   2>/dev/null 로 stderr 를 버리면 표가 통째로 사라져서 아무것도 못 찾습니다.
#   그래서 2>&1 로 둘을 합쳐서 읽습니다.
#   ★ 주소를 추측하지 않습니다 ★
#   예전에는 못 찾으면 "https://<이름>.vercel.app" 으로 추측했습니다. 그런데
#   그 주소는 남이 이미 쓰고 있을 수 있습니다. 실제로 speed-test 라는 이름으로
#   만들었더니 speed-test.vercel.app 은 생판 남의 사이트였고, 버셀은 겹치지
#   않는 speed-test-five-fawn.vercel.app 을 새로 배정했습니다.
#   추측한 주소를 확인하면 "남의 사이트 상태"를 내 것인 양 보고하게 됩니다.
#   그래서 못 찾으면 빈 값을 돌려주고, 부르는 쪽에서 처리합니다.
site_url() {
  local name="$1" url
  url="$(vc project ls 2>&1 | awk -v n="$name" '$1==n {print $2}' | head -1 || true)"
  printf '%s' "$url"
}

# ----------------------------------------------------------------------------
# http_code : 로그인하지 않은 상태로 주소를 열어 응답 코드를 봅니다.
#   curl 이 리다이렉트를 따라가면 코드가 여러 번 찍히므로 마지막 3글자만 씁니다.
# ----------------------------------------------------------------------------
http_code() {
  local code
  code="$(curl -s -o /dev/null -w '%{http_code}' -L --max-time 30 "$1" 2>/dev/null || true)"
  code="${code: -3}"
  printf '%s' "${code:-000}"
}

# ----------------------------------------------------------------------------
# page_title : 그 주소가 실제로 어떤 페이지를 내려주는지 확인합니다.
#   버셀 잠금이 걸려 있으면 "Login – Vercel" 이 나옵니다.
#   그래서 "정말 잠겼는지" 를 눈이 아니라 응답으로 확인할 수 있습니다.
# ----------------------------------------------------------------------------
page_title() {
  curl -s -L --max-time 30 "$1" 2>/dev/null \
    | grep -oE '<title>[^<]*</title>' | head -1 \
    | sed 's/<[^>]*>//g' || true
}
