#!/usr/bin/env bash
# ============================================================================
#  publish.sh — 고친 내용을 깃허브에 올리고 버셀에 배포한다
# ----------------------------------------------------------------------------
#  사용법
#      bash publish.sh "무엇을 고쳤는지"
#      bash publish.sh --dir "프로젝트폴더" "무엇을 고쳤는지"
#
#  프로젝트 폴더 안에서 실행하면 --dir 을 생략해도 됩니다.
#
#  하는 일
#      1) 바뀐 파일이 있으면 커밋 (없으면 건너뜀)
#      2) 깃허브에 업로드 (원격이 없으면 저장소를 새로 만들어 줌)
#      3) 버셀에 배포
#      4) 실제로 열리는지 확인
# ============================================================================

source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib/common.sh"

MSG="변경사항 반영"        # 커밋 메시지 기본값
DIR="$PWD"                 # 기본은 지금 있는 폴더

while [ $# -gt 0 ]; do
  case "$1" in
    --dir) DIR="${2:-}"; shift ;;
    *)     MSG="$1" ;;
  esac
  shift
done

check_auth
cd "$DIR" || die "폴더를 찾을 수 없습니다: $DIR"

# git 저장소가 맞는지 확인합니다. 아니면 엉뚱한 곳에서 돌고 있는 것입니다.
git rev-parse --git-dir >/dev/null 2>&1 \
  || die "여기는 git 저장소가 아닙니다: $DIR
  프로젝트 폴더에서 실행하거나 --dir 로 폴더를 지정해 주세요."

NAME="$(basename "$DIR")"

# ----------------------------------------------------------------------------
# 1) 커밋
#    git status --porcelain 은 바뀐 파일 목록을 간단히 뱉습니다.
#    아무것도 안 나오면 바뀐 게 없다는 뜻이라 커밋을 건너뜁니다.
# ----------------------------------------------------------------------------
if [ -n "$(git status --porcelain)" ]; then
  step "바뀐 파일 기록   \"$MSG\""
  git add -A
  git commit -q -m "$MSG"
else
  step "바뀐 파일이 없어 커밋은 건너뜁니다"
fi

# ----------------------------------------------------------------------------
# 2) 깃허브에 업로드
#    origin(원격 저장소)이 없으면 저장소부터 만들어 줍니다.
# ----------------------------------------------------------------------------
if git remote get-url origin >/dev/null 2>&1; then
  step "깃허브에 업로드"
  git push -q || die "업로드 실패. 인터넷 연결이나 권한을 확인해 주세요."
else
  step "원격 저장소가 없어 새로 만듭니다 (비공개)"
  check_name "$NAME"
  "$GH" repo create "$NAME" --private --source=. --remote=origin --push >/dev/null 2>&1 \
    || die "저장소 만들기 실패"
fi

# ----------------------------------------------------------------------------
# 3) 버셀 배포
# ----------------------------------------------------------------------------
step "버셀에 배포"
OUT="$TOOLS/.out_$$.txt"; ERR="$TOOLS/.err_$$.txt"
trap 'rm -f "$OUT" "$ERR"' EXIT
if ! vc deploy --prod --yes >"$OUT" 2>"$ERR"; then
  printf '\n배포 실패 내용:\n'; tail -6 "$ERR"
  die "버셀 배포에 실패했습니다."
fi
SITE="$(grep -oE 'Aliased +https://[^ ]+' "$ERR" | head -1 | awk '{print $2}')"
[ -n "$SITE" ] || SITE="https://$(grep -oE '"url": *"[^"]+"' "$OUT" | head -1 | sed 's/.*"url": *"//;s/"//')"

# ----------------------------------------------------------------------------
# 4) 확인
# ----------------------------------------------------------------------------
step "실제로 열리는지 확인"
CODE="$(http_code "$SITE")"
SEEN="$(page_title "$SITE")"

printf '\n─────────────────────────────────────────────\n'
printf ' 사이트  %s   (HTTP %s)\n' "$SITE" "$CODE"
printf ' 보이는 제목  %s\n' "${SEEN:--}"
printf ' 저장소  https://github.com/%s/%s\n' "$GH_OWNER" "$NAME"
printf ' 커밋    %s\n' "$(git rev-parse --short HEAD)"
printf '─────────────────────────────────────────────\n'
